import type { DaysPattern } from "@/lib/schedule";
import type { CaregiverLinkStatus } from "@/lib/caregiver";
import type { RiskLevel } from "@/lib/risk";

export type Role = "patient" | "caregiver";

export type Profile = {
  id: string;
  role: Role;
  name: string | null;
  phone: string | null;
  language: string;
};

export type PatientProfile = {
  id: string;
  name: string;
  age: number | null;
  allergies: string[];
  conditions: string[];
  breakfast_time: string | null;
  lunch_time: string | null;
  dinner_time: string | null;
};

/** Lightweight shape passed to the client profile switcher. */
export type PatientOption = {
  id: string;
  name: string;
  age: number | null;
};

/**
 * Health information shown on the /medicine/[id] "Info" tab.
 *
 * Generated by the LLM from the medicine name and composition only (never
 * personal data). The disclaimer always accompanies it. Kept here, not in
 * lib/medicine-info.ts, so client components can import the type without
 * pulling any server-only code into the bundle.
 */
export type MedicineInfoWarnings = {
  when_not_to_take: string[];
  food_instruction: string;
  alcohol: string;
  pregnancy_note: string;
};

export type MedicineInfo = {
  uses: string;
  usual_dosage: string;
  common_side_effects: string[];
  warnings: MedicineInfoWarnings;
  simple_explanation: string;
  simple_explanation_hi: string;
  sources: string[];
  source_label: string;
  /** False until Phase 3B wires TinyFish live sources. */
  live_source_used: boolean;
  generated_at: string;
  model: string;
};

export type MedicineInfoPayload = MedicineInfo & {
  cached: boolean;
  /** The model that answered the fallback chain (equals `model`). */
  model_used: string;
};

/** The statuses a `dose_logs.status` row can hold (matches the DB check). */
export type DoseStatus =
  | "pending"
  | "taken"
  | "skipped"
  | "snoozed"
  | "missed";

/** One row in the home "today" timeline (already joined to its medicine). */
export type TimelineDose = {
  id: string;
  due_at: string;
  status: DoseStatus;
  acted_at: string | null;
  medicine_name: string;
  /** "Day 3 of 5" while a course runs, or null. */
  course: string | null;
  schedule_id: string;
  days_pattern: DaysPattern;
};

/** An as-needed medicine shown on the home screen ("Took one now"). */
export type AsNeededMedicine = {
  schedule_id: string;
  medicine_id: string;
  name: string;
};

/* ------------------------------------------------------------------ */
/* Caregiver dashboard                                                 */
/* ------------------------------------------------------------------ */

/**
 * Weekly adherence for one patient. `percent` is null when there is nothing to
 * measure yet (no taken/missed/skipped doses in the window) so the UI can show
 * "No data yet" instead of a misleading 0%.
 */
export type Adherence = {
  taken: number;
  missed: number;
  skipped: number;
  total: number;
  percent: number | null;
};

/** A patient the signed-in caregiver is actively linked to (consent given). */
export type CaregiverPatient = {
  id: string;
  name: string;
};

/** Everything the dashboard shows for one linked patient. */
export type CaregiverPatientSummary = {
  patient: CaregiverPatient;
  /** Today's doses in Asia/Kolkata, newest handled by the UI. */
  doses: TimelineDose[];
  adherence: Adherence;
};

/** A caregiver<->patient link row as seen by the caregiver (no patient name
 * yet while the request is still pending approval). */
export type CaregiverLinkSummary = {
  id: string;
  status: CaregiverLinkStatus;
  consent_given: boolean;
  patient_id: string;
  patient_name: string | null;
};

/** One medicine in the read-only caregiver list, with the batch-alert flag. */
export type CaregiverMedicine = {
  id: string;
  name: string;
  batch_no: string | null;
  expiry_date: string | null;
  risk_level: RiskLevel | null;
  /** True when a stored risk reason carries the official batch-alert code. */
  has_batch_alert: boolean;
  /** Plain-language alert text (English) when `has_batch_alert` is true. */
  alert_message: string | null;
};

/** One row of the read-only dose history list. */
export type CaregiverHistoryRow = {
  id: string;
  due_at: string;
  status: DoseStatus;
  acted_at: string | null;
  medicine_name: string;
};
